#!/usr/bin/env python3
"""Progress page for Bounce Touch 3D / Página de progreso de Bounce Touch 3D.

Two measures: game features (docs/features.tsv: done / partial / todo) and engine rules by evidence
(tables under «Reglas del motor y su evidencia» in docs/GUIONES.md). Writes progress.json, progress.svg
and index.html. Usage / Uso: python3 tools/progress.py [out_dir]   (default: _site/). No dependencies.
"""
import html
import json
import os
import re
import sys
from collections import Counter
from datetime import datetime, timezone

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
REPO = "https://github.com/alexroses47/Bounce-Touch-3D"
WEIGHT = {"done": 1.0, "partial": 0.5, "todo": 0.0}
STATE_LABEL = {
    "V-test": "Verified: differential test vs original / Verificada: test contra el original",
    "V-traza": "Verified: trace of the original / Verificada: traza del original",
    "V-lectura": "Read in the binary, not tested yet / Leída en el binario, sin test",
    "Pendiente": "Pending: no evidence yet / Pendiente: sin evidencia",
    "Port": "Port invention / Invención del port",
}


def features():
    rows = []
    for line in open(os.path.join(ROOT, "docs", "features.tsv"), encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        area, en, es, status = line.rstrip("\n").split("\t")
        rows.append({"area": area, "en": en, "es": es, "status": status})
    return rows


def rules():
    text = open(os.path.join(ROOT, "docs", "GUIONES.md"), encoding="utf-8").read()
    text = text[text.index("## Reglas del motor y su evidencia"):]
    out, section = [], ""
    for line in text.splitlines():
        if line.startswith("### "):
            section = line[4:].strip()
        if not line.startswith("| ") or line.startswith("| Regla") or line.startswith("|---"):
            continue
        cells = [c.strip() for c in line.replace("\\|", "¦").strip("|").split("|")]
        if len(cells) < 2:
            continue
        state = next((k for k in STATE_LABEL if cells[1].startswith(k)), None)
        if state:
            out.append({"section": section, "state": state, "rule": re.sub(r"[`*]", "", cells[0]).replace("¦", "|")})
    return out


def bar_svg(pct):
    w = 400
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w + 70}" height="24">'
            f'<rect width="{w}" height="24" fill="#6e7681"/><rect width="{int(w * pct / 100)}" height="24" fill="#2ea043"/>'
            f'<text x="{w + 8}" y="17" font-family="sans-serif" font-size="14">{pct:.0f}%</text></svg>')


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "_site")
    os.makedirs(out, exist_ok=True)
    feats = features()
    pct = 100.0 * sum(WEIGHT[f["status"]] for f in feats) / len(feats)
    rl = rules()
    states = Counter(r["state"] for r in rl)
    verified = states["V-test"] + states["V-traza"]
    data = {"generated": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"), "percent": round(pct, 1),
            "features": feats, "rules": {"total": len(rl), "by_state": dict(states)}}
    json.dump(data, open(os.path.join(out, "progress.json"), "w"), indent=1, ensure_ascii=False)
    open(os.path.join(out, "progress.svg"), "w").write(bar_svg(pct))
    icon = {"done": "✅", "partial": "🟡", "todo": "⬜"}
    frows = "".join(f'<tr><td>{html.escape(f["area"])}</td><td>{html.escape(f["en"])}<br><small>{html.escape(f["es"])}</small></td>'
                    f'<td>{icon[f["status"]]} {f["status"]}</td></tr>' for f in feats)
    srows = "".join(f'<tr><td>{html.escape(STATE_LABEL[k])}</td><td>{states[k]}</td></tr>' for k in STATE_LABEL)
    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Bounce Touch 3D progress</title>
<style>body{{font-family:sans-serif;max-width:1000px;margin:auto;padding:16px;background:#fff;color:#1f2328}}
img{{max-width:100%}}table{{border-collapse:collapse;width:100%}}th,td{{border:1px solid #ccc;padding:2px 8px;text-align:left}}
td+td+td,th+th+th{{white-space:nowrap}}small{{color:#6e7681}}
@media(prefers-color-scheme:dark){{body{{background:#0d1117;color:#e6edf3}}th,td{{border-color:#30363d}}a{{color:#58a6ff}}}}</style>
</head><body>
<h1>Bounce Touch 3D — Progress / Progreso</h1>
<img src="progress.svg" alt="{pct:.0f}%">
<p>⚠️ Experimental demo / demo experimental. Game features: done = 1, partial = ½. /
Funciones del juego: hecho = 1, parcial = ½.</p>
<p>Generated by <a href="{REPO}/blob/main/tools/progress.py">tools/progress.py</a> on every push to <code>main</code>
({data["generated"]}). Raw numbers: <a href="progress.json">progress.json</a>.</p>
<h2>Game features / Funciones del juego</h2>
<table><tr><th>Area</th><th>Feature / Función</th><th>Status</th></tr>{frows}</table>
<h2>Engine rules by evidence / Reglas del motor por evidencia</h2>
<p>{len(rl)} rules reimplemented from the original binary; {verified} verified against the original game.
Details: <a href="{REPO}/blob/main/docs/GUIONES.md">docs/GUIONES.md</a>. /
{len(rl)} reglas reimplementadas a partir del binario original; {verified} verificadas contra el juego original.</p>
<table><tr><th>State / Estado</th><th>Rules / Reglas</th></tr>{srows}</table>
</body></html>
"""
    open(os.path.join(out, "index.html"), "w", encoding="utf-8").write(page)
    print(f"{out}: {pct:.0f}% features, {len(rl)} rules {dict(states)}")


if __name__ == "__main__":
    main()
